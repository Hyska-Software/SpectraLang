@dataclass(frozen=True)
class Entry:
    module: str
    function: str
    binding: str
    returns_value: bool
    ir_return: str


def catalog_path(root: Path) -> Path:
    return root / CATALOG


def load_catalog(root: Path = ROOT) -> dict[tuple[str, str], Entry]:
    """Index the catalog function entries by ``(module, function)``."""
    with catalog_path(root).open("rb") as handle:
        catalog = tomllib.load(handle)

    entries: dict[tuple[str, str], Entry] = {}
    for raw in catalog.get("entry", []):
        if str(raw.get("kind", "")) != "function":
            continue
        path = str(raw["path"])
        parts = path.split(".")
        module = ".".join(parts[2:-1]) if parts[1] == "api" else ".".join(parts[1:-1])
        key = (module, parts[-1])
        if key in entries:
            raise RuntimeError(f"duplicate catalog function {path!r}")
        entries[key] = Entry(
            module=module,
            function=parts[-1],
            binding=str(raw["binding"]),
            returns_value=bool(raw["returns_value"]),
            ir_return=str(raw["ir_return"]),
        )
    return entries


def binding_const_name(entry: Entry) -> str:
    """`std.fs.fs_read` -> `STD_FS_FS_READ_BINDING` (see contract build.rs)."""
    path = f"std.{entry.module}.{entry.function}"
    name = "".join(ch.upper() if ch.isalnum() else "_" for ch in path)
    return f"{name}_BINDING"


def render_ir(ir_return: str, indent: int) -> list[str]:
    """Render a catalog `ir_return` as the Rust `IRType` expression lines."""
    pad = " " * indent
    if ir_return in SIMPLE_IR:
        return [pad + SIMPLE_IR[ir_return]]
    if ir_return == "Error":
        return [pad + "builtin_error_ir_type()"]
    if ir_return.startswith("Result<") and ir_return.endswith(">"):
        inner = render_ir(ir_return[len("Result<") : -1], indent)
        return wrap_call("builtin_result_ir_type", inner)
    if ir_return == "Option<string>":
        return [
            pad + "IRType::Enum {",
            pad + '    name: "Option_string".to_string(),',
            pad + "    variants: vec![",
            pad + '        ("Some".to_string(), Some(vec![IRType::String])),',
            pad + '        ("None".to_string(), None),',
            pad + "    ],",
            pad + "}",
        ]
    if re.fullmatch(r"(List|Map|Set|Iterator|Stack|Queue)<.*>", ir_return):
        name = re.sub(r"[<>,]", "_", ir_return).rstrip("_")
        return [
            pad + "IRType::Struct {",
            pad + f'    name: "{name}".to_string(),',
            pad + "    fields: Vec::new(),",
            pad + "}",
        ]
    match = re.fullmatch(r"Tensor<([a-z0-9]+)(?:,rank=(\d+))?>", ir_return)
    if match:
        dtype = {"float": "IRType::Float", "int": "IRType::Int"}[match.group(1)]
        rank = match.group(2)
        return [
            pad + "IRType::Tensor {",
            pad + f"    dtype: Box::new({dtype}),",
            pad + f"    rank: {f'Some({rank})' if rank else 'None'},",
            pad + "    dims: None,",
            pad + "    layout: None,",
            pad + "    device: None,",
            pad + "}",
        ]
    raise RuntimeError(f"no IRType rendering for catalog ir_return {ir_return!r}")


def wrap_call(function: str, inner: list[str]) -> list[str]:
    """`call(` + the expression's first line, closing on the expression's last."""
    first = inner[0].lstrip()
    if len(inner) == 1:
        return [inner[0][: len(inner[0]) - len(first)] + f"{function}({first})"]
    return [inner[0][: len(inner[0]) - len(first)] + f"{function}({first}", *inner[1:-1], inner[-1] + ")"]


def runtime_expression(entry: Entry, style: str) -> str:
    alias = RUNTIME_ALIASES.get((entry.module, entry.function))
    if alias is not None:
        return f'"{alias}"'
    if style == STYLE_STRUCT and entry.function in SHARED_BINDINGS.get(entry.module, ()):
        return f"spectra_contract::{binding_const_name(entry)}"
    return f'"{entry.binding}"'


def arm_style(
    layout: FileLayout, catalog: dict[tuple[str, str], Entry], module: str, function: str
) -> str:
    """The rendering style LAYOUT prescribes for one arm."""
    for group in layout.groups:
        if group.module != module:
            continue
        for item in group.names.split():
            if item.split("@", 1)[0] != function:
                continue
            if "@" in item:
                return item.split("@", 1)[1]
            entry = catalog.get((module, function))
            if entry is None:
                raise RuntimeError(f"{layout.path}: no catalog entry for {module}.{function}")
            return default_style(layout.style, entry)
    raise RuntimeError(f"{layout.path}: {module}.{function} is not in the layout")


def default_style(style: str, entry: Entry) -> str:
    if style == STYLE_STRUCT:
        return STYLE_STRUCT
    return DEFAULT_HELPER.get(entry.ir_return, STYLE_STRUCT)


def emit_arm(entry: Entry, style: str, indent: str = "        ") -> list[str]:
    """Render one match arm, byte-identical to the legacy hand-written text."""
    runtime = runtime_expression(entry, style)
    head = f'{indent}("{entry.module}", "{entry.function}")'
    if style != STYLE_STRUCT:
        ir_return, returns_value = HELPER_IR[style]
        if ir_return != entry.ir_return or returns_value != entry.returns_value:
            raise RuntimeError(
                f"{entry.module}.{entry.function}: {style} returns {ir_return}/"
                f"{returns_value} but the catalog says {entry.ir_return}/"
                f"{entry.returns_value}; update LAYOUT or the catalog"
            )
        single = f'{head} => Some({style}({runtime})),'
        if len(single) <= MAX_WIDTH:
            return [single]
        body = f"Some({style}({runtime}))"
        call_arg = f"{style}({runtime})"
        if len(f"            {body}") <= MAX_WIDTH and len(call_arg) <= FN_CALL_WIDTH:
            return [f"{head} => {{", f"            {body}", f"{indent}}}"]
        return [f"{head} => Some({style}(", f'            "{entry.binding}",' if runtime == f'"{entry.binding}"' else f"            {runtime},", f"{indent})),"]

    type_lines = render_ir(entry.ir_return, 12)
    if len(type_lines) == 1:
        type_block = [f"            return_type: {type_lines[0].strip()},"]
    else:
        type_block = [f"            return_type: {type_lines[0].strip()}"]
        type_block += type_lines[1:-1]
        type_block.append(type_lines[-1] + ",")
    return [
        f"{head} => Some(HostFunctionDescriptor {{",
        f"            runtime_name: {runtime},",
        *type_block,
        f"            returns_value: {str(entry.returns_value).lower()},",
        f"{indent}}}),",
    ]


def render_file(layout: FileLayout, catalog: dict[tuple[str, str], Entry]) -> str:
    lines = [HEADER.format(summary=layout.summary)]
    lines += [
        "use super::*;",
        "",
        f"pub(crate) fn {layout.function}(",
        "    module: &str,",
        "    function: &str,",
        ") -> Option<HostFunctionDescriptor> {",
        "    match (module, function) {",
    ]
    for group in layout.groups:
        if group.comment is not None:
            lines.append(group.comment)
        for item in group.names.split():
            function = item.split("@", 1)[0]
            entry = catalog.get((group.module, function))
            if entry is None:
                raise RuntimeError(f"{layout.path}: no catalog entry for {group.module}.{function}")
            lines += emit_arm(entry, arm_style(layout, catalog, group.module, function))
    lines += layout.tail
    return "\n".join(lines) + "\n"


def numeric_wrapping(catalog: dict[tuple[str, str], Entry]) -> list[tuple[bool, str, list[str]]]:
    """`(signed, width, function names)` groups in dispatch order."""
    groups: dict[tuple[bool, str], dict[str, str]] = {}
    for (module, function), entry in catalog.items():
        if module != "numeric":
            continue
        match = WRAPPING_RE.fullmatch(function)
        if match is None:
            continue
        op, prefix, width = match.groups()
        if entry.ir_return != f"ExactInt<{prefix}{width}>":
            raise RuntimeError(
                f"numeric.{function}: catalog ir_return {entry.ir_return!r} does not match "
                f"the wrapping width {prefix}{width}"
            )
        groups.setdefault((prefix == "i", width), {})[op] = function
    if not groups:
        raise RuntimeError("the catalog has no std.numeric wrapping_* entries")
    ordered = []
    for signed in (True, False):
        for width in INT_WIDTHS:
            ops = groups.get((signed, width))
            if ops is None:
                continue
            missing = [op for op in WRAPPING_OPS if op not in ops]
            if missing:
                raise RuntimeError(f"numeric wrapping_{{{','.join(missing)}}}_{width} is missing")
            ordered.append((signed, width, [ops[op] for op in WRAPPING_OPS]))
    return ordered


def render_numeric(catalog: dict[tuple[str, str], Entry]) -> str:
    lines = [HEADER.format(summary=NUMERIC_SUMMARY)]
    lines += [
        "use super::*;",
        "",
        f"pub(crate) fn {NUMERIC_FUNCTION}(",
        "    module: &str,",
        "    function: &str,",
        ") -> Option<HostFunctionDescriptor> {",
        '    if module == "numeric" {',
    ]
    conversions = sorted(
        (entry for (module, _), entry in catalog.items() if module == "numeric" and entry.ir_return.startswith("ExactFloat<")),
        key=lambda e: e.function,
    )
    for entry in conversions:
        width = entry.ir_return[len("ExactFloat<") : -1].upper()
        lines += [
            f'        if function == "{entry.function}" {{',
            "            return Some(HostFunctionDescriptor {",
            f'                runtime_name: "{entry.binding}",',
            "                return_type: IRType::ExactFloat {",
            f"                    width: IRFloatWidth::{width},",
            "                },",
            f"                returns_value: {str(entry.returns_value).lower()},",
            "            });",
            "        }",
        ]
    checked_ints = sorted(
        (
            entry
            for (module, _), entry in catalog.items()
            if module == "numeric"
            and entry.function.startswith("checked_")
            and entry.ir_return.startswith("ExactInt<")
        ),
        key=lambda e: e.function,
    )
    for entry in checked_ints:
        width_text = entry.ir_return[len("ExactInt<") : -1]
        if not width_text or width_text[0] not in "iu" or width_text[1:] not in INT_WIDTHS:
            raise RuntimeError(
                f"numeric checked function has unsupported exact integer return: "
                f"{entry.function} -> {entry.ir_return}"
            )
        signed = width_text[0] == "i"
        width = width_text[1:]
        lines += [
            f'        if function == "{entry.function}" {{',
            "            return Some(HostFunctionDescriptor {",
            f'                runtime_name: "{entry.binding}",',
            "                return_type: IRType::ExactInt {",
            f"                    signed: {str(signed).lower()},",
            f"                    width: IRIntWidth::I{width},",
            "                },",
            f"                returns_value: {str(entry.returns_value).lower()},",
            "            });",
            "        }",
        ]
    lines += [
        "        let (signed, width): (bool, IRIntWidth) = match function {",
    ]
    for signed, width, functions in numeric_wrapping(catalog):
        pattern = " | ".join(f'"{name}"' for name in functions)
        # `IntWidth` only has signed variants; the unsigned widths are the same
        # enum values paired with `signed = false`.
        single = f"            {pattern} => ({str(signed).lower()}, IRIntWidth::I{width}),"
        if len(single) <= MAX_WIDTH:
            lines.append(single)
        else:
            lines += [
                f"            {pattern} => {{",
                f"                ({str(signed).lower()}, IRIntWidth::I{width})",
                "            }",
            ]
    lines += [
        "            _ => return None,",
        "        };",
        "        return Some(HostFunctionDescriptor {",
        '            runtime_name: Box::leak(format!("spectra.std.numeric.{function}").into_boxed_str()),',
        "            return_type: IRType::ExactInt { signed, width },",
        "            returns_value: true,",
        "        });",
        "    }",
        "    lookup_std_host_group_math_io_error(module, function)",
        "        .or_else(|| lookup_std_host_group_tensor_ml(module, function))",
        "        .or_else(|| lookup_std_host_group_collections_string(module, function))",
        "        .or_else(|| lookup_std_host_group_convert_time(module, function))",
        "        .or_else(|| lookup_std_host_group_fs_env_result(module, function))",
        "}",
    ]
    return "\n".join(lines) + "\n"


def place_new_functions(catalog: dict[tuple[str, str], Entry]) -> tuple[FileLayout, ...]:
    """`LAYOUT` plus catalog functions that are not listed anywhere yet.

    A catalog function whose module occupies exactly one group across every
    generated file is appended to that group in catalog order, so adding a native
    function to an existing namespace needs no hand edit.  A function in a module
    that is split over several groups or files (``std.collections`` is shared by
    three files) is left for :func:`check_coverage` to report rather than placed
    on a guess.
    """
    slots: dict[str, list[tuple[int, int]]] = {}
    listed: dict[str, set[str]] = {}
    for layout_index, layout in enumerate(LAYOUT):
        for group_index, group in enumerate(layout.groups):
            if group.module is None:
                continue
            slots.setdefault(group.module, []).append((layout_index, group_index))
            listed.setdefault(group.module, set()).update(
                item.split("@", 1)[0] for item in group.names.split()
            )

    additions: dict[tuple[int, int], list[str]] = {}
    for (module, function), _ in catalog.items():
        if module not in slots or function in EXCLUDED.get(module, ()):
            continue
        if function in listed[module]:
            continue
        if len(slots[module]) == 1:
            additions.setdefault(slots[module][0], []).append(function)

    placed = []
    for layout_index, layout in enumerate(LAYOUT):
        groups = []
        for group_index, group in enumerate(layout.groups):
            extra = additions.get((layout_index, group_index), [])
            names = " ".join(filter(None, [group.names, " ".join(extra)]))
            groups.append(Group(group.module, names, group.comment))
        placed.append(replace(layout, groups=tuple(groups)))
    return tuple(placed)


def check_coverage(
    catalog: dict[tuple[str, str], Entry], layouts: tuple[FileLayout, ...]
) -> list[str]:
    """Every catalog function in an owned namespace must be emitted or excluded."""
    problems: list[str] = []
    slots: dict[str, int] = {}
    emitted: dict[str, set[str]] = {}
    for layout in layouts:
        for group in layout.groups:
            if group.module is None:
                continue
            slots[group.module] = slots.get(group.module, 0) + 1
            emitted.setdefault(group.module, set()).update(
                item.split("@", 1)[0] for item in group.names.split()
            )

    for module in sorted(emitted):
        entries = {function for (entry_module, function) in catalog if entry_module == module}
        excluded = EXCLUDED.get(module, frozenset())
        missing = sorted(entries - emitted[module] - excluded)
        if missing:
            problems.append(
                f"{module}: catalog functions missing from LAYOUT: {missing} "
                f"(the module is spread over {slots[module]} groups; place them by hand)"
            )
        stale = sorted(excluded - entries)
        if stale:
            problems.append(f"{module}: EXCLUDED lists unknown catalog functions: {stale}")
        both = sorted(emitted[module] & excluded)
        if both:
            problems.append(f"{module}: functions are both emitted and excluded: {both}")

    numeric = {function for (module, function) in catalog if module == "numeric"}
    selected = {
        function
        for function in numeric
        if WRAPPING_RE.fullmatch(function)
        or catalog[("numeric", function)].ir_return.startswith("ExactFloat<")
        or catalog[("numeric", function)].ir_return.startswith("ExactInt<")
    }
    unowned = sorted(numeric - selected)
    if unowned:
        problems.append(f"numeric: catalog functions that no lowering owns: {unowned}")
    return problems


def prepare(root: Path = ROOT) -> tuple[dict[tuple[str, str], Entry], tuple[FileLayout, ...]]:
    """Load the catalog, place new functions and fail on coverage gaps."""
    catalog = load_catalog(root)
    layouts = place_new_functions(catalog)
    problems = check_coverage(catalog, layouts)
    if problems:
        raise RuntimeError(
            "the lowering tables do not cover the catalog:\n  " + "\n  ".join(problems)
        )
    return catalog, layouts


def render_all(root: Path = ROOT) -> dict[str, str]:
    catalog, layouts = prepare(root)
    rendered = {layout.path: render_file(layout, catalog) for layout in layouts}
    rendered[NUMERIC_PATH] = render_numeric(catalog)
    return rendered


def auto_placed_names(layouts: tuple[FileLayout, ...]) -> list[str]:
    """Catalog functions the generator placed in a group on its own."""
    placed: list[str] = []
    for layout, base in zip(layouts, LAYOUT):
        listed = {
            item.split("@", 1)[0] for group in base.groups for item in group.names.split()
        }
        for group in layout.groups:
            for item in group.names.split():
                name = item.split("@", 1)[0]
                if name not in listed:
                    placed.append(f"{group.module}.{name}")
    return placed


def arm_count(layouts: tuple[FileLayout, ...]) -> int:
    return sum(len(group.names.split()) for layout in layouts for group in layout.groups)


def extract_layout(
    path: Path,
) -> tuple[str, tuple[tuple[str | None, str, str | None], ...], str]:
    """Re-derive a table file's arm layout (order, banners, styles) from its text.

    This is the step-1 half of the migration: the descriptor content of an arm is
    irrelevant here, only the order, the section banners and the rendering style,
    which is what ``LAYOUT`` records.
    """
    lines = path.read_text(encoding="utf-8").split("\n")
    function = next(
        line.split("fn ", 1)[1].split("(", 1)[0]
        for line in lines
        if line.startswith("pub(crate) fn ")
    )
    start = next(i for i, line in enumerate(lines) if line.strip() == "match (module, function) {")
    end = next(i for i, line in enumerate(lines) if i > start and line.strip() == "_ => None,")

    groups: list[tuple[str | None, list[tuple[str, str]], str | None]] = []
    banner: str | None = None
    index = start + 1
    while index < end:
        stripped = lines[index].strip()
        if stripped.startswith("//"):
            banner = f"{banner}\n{lines[index]}" if banner else lines[index]
            index += 1
            continue
        head = re.match(r'\("([\w.]+)", "(\w+)"\)', stripped)
        if head is None:
            index += 1
            continue
        module, name = head.groups()
        block = [lines[index]]
        depth = sum(lines[index].count(ch) for ch in "({") - sum(
            lines[index].count(ch) for ch in ")}"
        )
        while depth > 0:
            index += 1
            block.append(lines[index])
            depth += sum(lines[index].count(ch) for ch in "({") - sum(
                lines[index].count(ch) for ch in ")}"
            )
        index += 1
        text = "\n".join(block)
        if "HostFunctionDescriptor {" in text:
            style = STYLE_STRUCT
        else:
            helper = re.search(r"Some\((host_\w+)\(", text)
            if helper is None:
                raise RuntimeError(f"{path}: cannot classify the arm for {module}.{name}")
            style = helper.group(1)
        if not groups or groups[-1][0] != module or banner is not None:
            groups.append((module, [], banner))
            banner = None
        groups[-1][1].append((name, style))
    if banner is not None:
        groups.append((None, [], banner))

    # The file-level style is the majority rendering; every arm that deviates
    # carries an explicit `@<style>` marker in LAYOUT.
    styles = [STYLE_STRUCT if style == STYLE_STRUCT else STYLE_HELPER for _, names, _ in groups for _, style in names]
    majority = STYLE_HELPER if styles.count(STYLE_HELPER) >= styles.count(STYLE_STRUCT) else STYLE_STRUCT
    return function, tuple((module, tuple(names), banner) for module, names, banner in groups), majority


def check_from_source(root: Path = ROOT) -> list[str]:
    """Step 1 proof: the embedded LAYOUT equals the checked-in tables' layout.

    The on-disk order, section banners and per-arm rendering style are re-derived
    from the file text and compared with ``LAYOUT``; the expected style of an arm
    is the one the generator would emit for it.
    """
    catalog, layouts = prepare(root)
    problems: list[str] = []
    for layout in layouts:
        path = root / layout.path
        if not path.exists():
            problems.append(f"{layout.path}: missing")
            continue
        function, groups, majority = extract_layout(path)
        if function != layout.function:
            problems.append(f"{layout.path}: function {function} != {layout.function}")
        if majority != layout.style:
            problems.append(f"{layout.path}: file style {majority} != {layout.style}")
        expected = tuple(
            (group.module, tuple(item.split("@", 1)[0] for item in group.names.split()), group.comment)
            for group in layout.groups
        )
        observed = tuple((module, tuple(name for name, _ in names), banner) for module, names, banner in groups)
        if observed != expected:
            for index, (got, want) in enumerate(zip(observed, expected)):
                if got != want:
                    problems.append(
                        f"{layout.path}: group {index} differs\n  on disk: {got}\n  LAYOUT:  {want}"
                    )
                    break
            else:
                problems.append(f"{layout.path}: group count {len(observed)} != {len(expected)}")
            continue
        for module, names, _ in groups:
            if module is None:
                continue
            for name, style in names:
                if style != arm_style(layout, catalog, module, name):
                    problems.append(
                        f"{layout.path}: {module}.{name} renders as {style}, "
                        f"LAYOUT says {arm_style(layout, catalog, module, name)}"
                    )
    return problems


def stale(rendered: dict[str, str], root: Path = ROOT) -> list[str]:
    report = []
    for relative, text in rendered.items():
        path = root / relative
        if not path.exists():
            report.append(f"{relative} is missing; run `python scripts/generate_lowering_tables.py`")
            continue
        raw = path.read_bytes()
        if b"\r\n" in raw:
            report.append(
                f"{relative} uses CRLF line endings; run "
                f"`python scripts/generate_lowering_tables.py` (the generator writes LF)"
            )
            continue
        current = raw.decode("utf-8")
        if current == text:
            continue
        diff = list(
            difflib.unified_diff(
                current.splitlines(),
                text.splitlines(),
                fromfile=f"{relative} (on disk)",
                tofile=f"{relative} (generated)",
                lineterm="",
                n=1,
            )
        )
        hint = "\n".join(diff[:24]) or f"{relative}: file is empty"
        report.append(
            f"{relative} is stale; run `python scripts/generate_lowering_tables.py`:\n{hint}"
        )
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail (non-zero) when a generated file is stale instead of writing it",
    )
    parser.add_argument(
        "--from-source",
        action="store_true",
        help="re-derive the layout from the checked-in files and compare it with LAYOUT",
    )
    args = parser.parse_args()

    if args.from_source:
        problems = check_from_source(ROOT)
        if problems:
            print(
                "R-3207 failure: the checked-in tables drifted from the catalog layout:",
                file=sys.stderr,
            )
            for problem in problems:
                print(f"  {problem}", file=sys.stderr)
            return 1
        _, layouts = prepare(ROOT)
        print(
            f"the checked-in tables match LAYOUT "
            f"({arm_count(layouts)} arms across {len(LAYOUT)} files)"
        )
        return 0

    rendered = render_all(ROOT)
    _, layouts = prepare(ROOT)
    placed = auto_placed_names(layouts)
    for name in placed:
        print(f"placed new catalog function {name} at the end of its group")
    if args.check:
        report = stale(rendered, ROOT)
        if report:
            for entry in report:
                print(f"R-3207 failure: {entry}", file=sys.stderr)
            return 1
        print(f"the lowering tables match the catalog ({arm_count(layouts)} generated arms)")
        return 0

    for relative, text in rendered.items():
        # `newline=""` keeps the generated files LF, like every other Rust source
        # in the repository, regardless of the host platform.
        (ROOT / relative).write_text(text, encoding="utf-8", newline="")
    print(
        f"generated {arm_count(layouts)} arms across {len(rendered)} lowering tables"
        f" ({len(placed)} placed from the catalog)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
