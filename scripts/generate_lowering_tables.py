#!/usr/bin/env python3
"""Generate the mid-end host-call lowering tables from the typed STD catalog.

`midend/src/lowering_std_api.rs` and the six `lowering_std_host_*.rs` files used
to repeat, by hand, one descriptor per native function: the catalog binding, the
IR return type and the `returns_value` flag.  This generator removes that copy.
The catalog (``packages/spectra-contract/catalog/stdlib.toml``) is the single
source of truth for the descriptor *content*; the generator owns the
*presentation* (file split, arm order, section comments and the
helper-vs-literal rendering style) through the ``LAYOUT`` table below.

The migration followed the two steps required by R-3207:

1. ``--from-source`` re-derives the presentation from the hand-written tables
   that were on disk and asserts it equals ``LAYOUT``, so the embedded
   presentation data is provably the legacy tables' layout instead of a retyped
   approximation.
2. The default mode renders the descriptor content from the catalog.  Run
   against the pre-migration tree it reproduced every arm byte-for-byte - the
   generated header was the only addition - which is what ``--check`` keeps
   verifying.

``--check`` re-renders in memory and fails when a generated file is stale, which
is how the drift guard catches a hand edit of a generated file.

The ``numeric`` file is special: it holds no descriptor table, only the
``checked_f32`` conversion and the ``wrapping_*`` width dispatch, both derived
from the catalog entries of that namespace (the remaining ``std.numeric``
functions are lowered by the compiler builtin tables).

Coverage is enforced both ways.  A catalog function in a namespace the tables
own but absent from ``LAYOUT`` is placed automatically when its module occupies a
single group (appended in catalog order); when the module is split over several
groups or files the generator fails and asks for a placement instead of
guessing.  ``EXCLUDED`` names the catalog functions that other lowerings own, and
the generator fails when an exclusion goes stale.

Usage:
    python scripts/generate_lowering_tables.py
    python scripts/generate_lowering_tables.py --check
    python scripts/generate_lowering_tables.py --from-source
"""

